#!/bin/bash
# Cloudron entrypoint.
#
# Cloudron starts this container with a read-only root filesystem, one writable volume (/app/data)
# and addon variables that may change on every restart (the database host, the Redis host, the
# mail credentials). So: secrets that must survive a restart live in /app/data/env.sh and are
# generated once; everything derived from the Cloudron environment is rebuilt on every start in
# /run/posthog/env.sh and never cached.
#
# The stack itself is run by supervisord (see supervisord.conf): ClickHouse, Redpanda, SeaweedFS,
# Caddy and the PostHog services, with bin/init.sh running the first-boot migrations before the
# services that need a schema are allowed to start.

set -eu -o pipefail

APP_DIR=/app/code
DATA_DIR=/app/data
RUN_DIR=/run/posthog

echo "==> PostHog (Cloudron) starting"

mkdir -p "${RUN_DIR}" /run/caddy /run/postgresql \
    /var/lib/posthog/clickhouse/data /var/lib/posthog/clickhouse/logs /var/lib/posthog/clickhouse/tmp \
    /var/lib/posthog/clickhouse/user_files /var/lib/posthog/clickhouse/format_schemas \
    /var/lib/posthog/clickhouse/access /var/lib/posthog/clickhouse/backups \
    /var/lib/posthog/redpanda /app/data/objectstorage /app/data/clickhouse-backup

# --- Secrets: generated once, kept in the volume ------------------------------------------------
if [[ ! -f "${DATA_DIR}/env.sh" ]]; then
    echo "==> Creating ${DATA_DIR}/env.sh"
    umask 077
    sed -e "s|##POSTHOG_SECRET##|$(openssl rand -hex 32)|" \
        -e "s|##ENCRYPTION_SALT_KEYS##|$(openssl rand -hex 16)|" \
        -e "s|##INTERNAL_API_SECRET##|$(openssl rand -hex 32)|" \
        -e "s|##CLICKHOUSE_APP_PASSWORD##|$(openssl rand -hex 16)|" \
        -e "s|##CLICKHOUSE_API_PASSWORD##|$(openssl rand -hex 16)|" \
        -e "s|##CLICKHOUSE_BILLING_PASSWORD##|$(openssl rand -hex 16)|" \
        -e "s|##CLICKHOUSE_DICT_READER_PASSWORD##|$(openssl rand -hex 16)|" \
        "${APP_DIR}/env.sh.template" > "${DATA_DIR}/env.sh"
    chmod 600 "${DATA_DIR}/env.sh"
fi

set +u
# shellcheck disable=SC1091
source "${DATA_DIR}/env.sh"
set -u

# --- Runtime environment: rebuilt from the Cloudron addons on every start -----------------------
umask 077
cat > "${RUN_DIR}/env.sh" <<EOF
# Generated by start.sh on every boot. Do not edit: Cloudron addon values change between restarts.

export POSTHOG_SECRET='${POSTHOG_SECRET}'
export SECRET_KEY='${POSTHOG_SECRET}'
export ENCRYPTION_SALT_KEYS='${ENCRYPTION_SALT_KEYS}'
export INTERNAL_API_SECRET='${INTERNAL_API_SECRET}'

# The hobby deployment mode: persons live in the main database (the persons partitioning
# migrations are production-only) and the managed-migrations checks are relaxed.
export DEPLOYMENT=hobby

export SITE_URL='https://${CLOUDRON_APP_DOMAIN:-localhost}'
export IS_BEHIND_PROXY=true
export TRUST_ALL_PROXIES=true
export DISABLE_SECURE_SSL_REDIRECT=true
export OPT_OUT_CAPTURE=true
export OTEL_SDK_DISABLED=true

export DATABASE_URL='${CLOUDRON_POSTGRESQL_URL:-}'
export PGHOST='${CLOUDRON_POSTGRESQL_HOST:-}'
export PGPORT='${CLOUDRON_POSTGRESQL_PORT:-5432}'
export PGUSER='${CLOUDRON_POSTGRESQL_USERNAME:-}'
export PGPASSWORD='${CLOUDRON_POSTGRESQL_PASSWORD:-}'
export PERSONS_DB_WRITER_URL='${CLOUDRON_POSTGRESQL_URL:-}'
export PERSONS_DB_READER_URL='${CLOUDRON_POSTGRESQL_URL:-}'
export PERSONS_DATABASE_URL='${CLOUDRON_POSTGRESQL_URL:-}'
export BEHAVIORAL_COHORTS_DATABASE_URL='${CLOUDRON_POSTGRESQL_URL:-}'
export READ_DATABASE_URL='${CLOUDRON_POSTGRESQL_URL:-}'
export WRITE_DATABASE_URL='${CLOUDRON_POSTGRESQL_URL:-}'
export PERSONS_READ_DATABASE_URL='${CLOUDRON_POSTGRESQL_URL:-}'
export PERSONS_WRITE_DATABASE_URL='${CLOUDRON_POSTGRESQL_URL:-}'
export PRIMARY_DATABASE_URL='${CLOUDRON_POSTGRESQL_URL:-}'
export FALLBACK_DATABASE_URL='${CLOUDRON_POSTGRESQL_URL:-}'

export REDIS_URL='${CLOUDRON_REDIS_URL:-redis://${CLOUDRON_REDIS_HOST:-127.0.0.1}:${CLOUDRON_REDIS_PORT:-6379}}'
export CDP_REDIS_HOST='${CLOUDRON_REDIS_HOST:-127.0.0.1}'
export CDP_REDIS_PORT='${CLOUDRON_REDIS_PORT:-6379}'
export CDP_VALKEY_HOST='${CLOUDRON_REDIS_HOST:-127.0.0.1}'
export CDP_VALKEY_PORT='${CLOUDRON_REDIS_PORT:-6379}'
export COOKIELESS_REDIS_HOST='${CLOUDRON_REDIS_HOST:-127.0.0.1}'
export COOKIELESS_REDIS_PORT='${CLOUDRON_REDIS_PORT:-6379}'
export LOGS_REDIS_HOST='${CLOUDRON_REDIS_HOST:-127.0.0.1}'
export LOGS_REDIS_PORT='${CLOUDRON_REDIS_PORT:-6379}'
export TRACES_REDIS_HOST='${CLOUDRON_REDIS_HOST:-127.0.0.1}'
export TRACES_REDIS_PORT='${CLOUDRON_REDIS_PORT:-6379}'
export SESSION_RECORDING_API_REDIS_HOST='${CLOUDRON_REDIS_HOST:-127.0.0.1}'
export SESSION_RECORDING_API_REDIS_PORT='${CLOUDRON_REDIS_PORT:-6379}'

# Everything below is inside this container (or, for Redis/Postgres/mail, a Cloudron addon).
export KAFKA_HOSTS='127.0.0.1:9092'
export KAFKA_INGESTION_PRODUCER_METADATA_BROKER_LIST='127.0.0.1:9092'

export CLICKHOUSE_HOST='127.0.0.1'
export CLICKHOUSE_DATABASE='posthog'
export CLICKHOUSE_SECURE=false
export CLICKHOUSE_VERIFY=false
# The dedicated per-workload ClickHouse users (app/api/billing/dict_reader) are deliberately not
# set. ClickHouse ships only `default`, nothing in this package creates extra accounts, and
# PostHog's own helpers fall back to the default user when CLICKHOUSE_<USER>_* is unset
# (posthog/clickhouse/client/connection.py, dictionaries.py). Setting them without a matching
# ClickHouse user fails every query and every dictionary reload with "Code: 516".
export CLICKHOUSE_LOGS_CLUSTER_HOST='127.0.0.1'
export CLICKHOUSE_LOGS_CLUSTER_SECURE=false

export OBJECT_STORAGE_ENABLED=true
export OBJECT_STORAGE_ENDPOINT='http://127.0.0.1:19000'
export OBJECT_STORAGE_PUBLIC_ENDPOINT='https://${CLOUDRON_APP_DOMAIN:-localhost}'
export OBJECT_STORAGE_ACCESS_KEY_ID='object_storage_root_user'
export OBJECT_STORAGE_SECRET_ACCESS_KEY='object_storage_root_password'
export OBJECT_STORAGE_FORCE_PATH_STYLE=true
export OBJECT_STORAGE_BUCKET='posthog'

export SESSION_RECORDING_V2_S3_ENDPOINT='http://127.0.0.1:19000'
export SESSION_RECORDING_V2_S3_BUCKET='posthog'
export SESSION_RECORDING_V2_S3_PREFIX='session_recordings'
export SESSION_RECORDING_V2_S3_ACCESS_KEY_ID='object_storage_root_user'
export SESSION_RECORDING_V2_S3_SECRET_ACCESS_KEY='object_storage_root_password'

export PERSONHOG_ENABLED=true
export PERSONHOG_ADDR='127.0.0.1:50052'

export FEATURE_FLAGS_SERVICE_URL='http://127.0.0.1:3001'
export CDP_API_URL='http://127.0.0.1:6738'
export RECORDING_API_URL='http://127.0.0.1:6740'
export CYCLOTRON_NODE_DATABASE_URL='${CLOUDRON_POSTGRESQL_URL:-}?options=-csearch_path%3Dcyclotron'

# Mail: the Cloudron sendmail addon (STARTTLS on the internal mail server).
export EMAIL_ENABLED='${CLOUDRON_MAIL_SMTP_SERVER:+true}'
export EMAIL_HOST='${CLOUDRON_MAIL_SMTP_SERVER:-}'
export EMAIL_PORT='${CLOUDRON_MAIL_SMTP_PORT:-587}'
export EMAIL_HOST_USER='${CLOUDRON_MAIL_SMTP_USERNAME:-}'
export EMAIL_HOST_PASSWORD='${CLOUDRON_MAIL_SMTP_PASSWORD:-}'
export EMAIL_USE_TLS=true
export EMAIL_DEFAULT_FROM='${CLOUDRON_MAIL_FROM_DISPLAY_NAME:+${CLOUDRON_MAIL_FROM_DISPLAY_NAME} <}${CLOUDRON_MAIL_FROM:-posthog@localhost}${CLOUDRON_MAIL_FROM_DISPLAY_NAME:+>}'

# Worker and web sizing: Celery defaults to one process per CPU (96 on the target host), which is
# how the standalone stack once exhausted its host's memory.
export WEB_CONCURRENCY=2
export GRANIAN_WORKERS=2
export GRANIAN_HOST=127.0.0.1
export GRANIAN_PORT=8010
export NODE_OPTIONS='--max-old-space-size=384'
# Size thread pools for a small app, not for the host's 96 cores.
export UV_THREADPOOL_SIZE=4
export TOKIO_WORKER_THREADS=2
export RAYON_NUM_THREADS=2
EOF
chmod 600 "${RUN_DIR}/env.sh"

# --- Render the proxy configuration -------------------------------------------------------------
cp "${APP_DIR}/conf/Caddyfile" "${RUN_DIR}/Caddyfile"

# --- Render the Redpanda configuration ----------------------------------------------------------
sed -e "s|##DATA_DIR##|/var/lib/posthog/redpanda|g" "${APP_DIR}/conf/redpanda.yaml" > "${RUN_DIR}/redpanda.yaml"

echo "==> Starting supervisor"
exec /usr/bin/supervisord --configuration /app/code/supervisord.conf --nodaemon
